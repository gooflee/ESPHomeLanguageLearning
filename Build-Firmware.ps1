[CmdletBinding()]
param(
    [switch]$GenerateHeadersOnly,
    [switch]$Compile,
    [switch]$Run,
    [string]$DevicePort = ""
)

$ErrorActionPreference = "Stop"
$ProjectRoot = Split-Path -Parent $MyInvocation.MyCommand.Path
$DataFile = Join-Path $ProjectRoot "data\Korean_sentences.txt"
$IncludeDir = Join-Path $ProjectRoot "include"
$HeaderOut = Join-Path $IncludeDir "default_sentences.h"
$GlyphsOut = Join-Path $IncludeDir "korean_glyphs.txt"
$YamlFile = Join-Path $ProjectRoot "sticky-korean.yaml"

if (-not (Test-Path $IncludeDir)) {
    New-Item -ItemType Directory -Path $IncludeDir -Force | Out-Null
}

if (-not (Test-Path $DataFile)) {
    throw "Data file not found at: $DataFile"
}

Write-Host "==> Reading Korean sentences from $DataFile ..." -ForegroundColor Cyan
$RawLines = Get-Content -Path $DataFile -Encoding UTF8
$Sentences = New-Object System.Collections.Generic.List[string]

foreach ($line in $RawLines) {
    $trimmed = $line.Trim()
    if ($trimmed.Length -gt 0) {
        $Sentences.Add($trimmed)
    }
}

Write-Host "==> Found $($Sentences.Count) Korean sentences." -ForegroundColor Green

# 1. Generate include/default_sentences.h (fallback deck when no MicroSD card is inserted)
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("#pragma once")
[void]$sb.AppendLine("// Auto-generated by Build-Firmware.ps1 from data/Korean_sentences.txt")
[void]$sb.AppendLine("// Do not edit manually; update data/Korean_sentences.txt and run Build-Firmware.ps1")
[void]$sb.AppendLine("#include <cstddef>")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("namespace sticky_korean {")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("static const size_t DEFAULT_KOREAN_SENTENCES_COUNT = $($Sentences.Count);")
[void]$sb.AppendLine("static const char *const DEFAULT_KOREAN_SENTENCES[$($Sentences.Count)] = {")

for ($i = 0; $i -lt $Sentences.Count; $i++) {
    $escaped = $Sentences[$i].Replace("\", "\\").Replace('"', '\"')
    $comma = if ($i -lt ($Sentences.Count - 1)) { "," } else { "" }
    [void]$sb.AppendLine("    `"$escaped`"$comma")
}

[void]$sb.AppendLine("};")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("}  // namespace sticky_korean")

$utf8NoBom = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllText($HeaderOut, $sb.ToString(), $utf8NoBom)
Write-Host "==> Generated fallback C++ header: $HeaderOut" -ForegroundColor Green

# 2. Extract unique characters into include/korean_glyphs.txt (useful if a TTF font is ever used)
$asciiUi = "[]()/0123456789.,?!-:~ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz"
$allText = ($Sentences -join "") + $asciiUi
$uniqueChars = ($allText.ToCharArray() | Where-Object { [int]$_ -ge 32 } | Sort-Object -Unique) -join ""
[System.IO.File]::WriteAllText($GlyphsOut, $uniqueChars, $utf8NoBom)
Write-Host "==> Extracted $($uniqueChars.Length) unique glyphs to: $GlyphsOut" -ForegroundColor Green

if ($GenerateHeadersOnly) {
    Write-Host "==> Header generation complete." -ForegroundColor Cyan
    exit 0
}

# 3. Locate ESPHome CLI (prefer local .venv\Scripts\esphome.exe if present)
$VenvEspHome = Join-Path $ProjectRoot ".venv\Scripts\esphome.exe"
if (Test-Path $VenvEspHome) {
    $esphomeExe = $VenvEspHome
} else {
    $esphomeCmd = Get-Command esphome -ErrorAction SilentlyContinue
    $esphomeExe = if ($esphomeCmd) { $esphomeCmd.Source } else { $null }
}

if (-not $esphomeExe) {
    Write-Host ""
    Write-Host "NOTE: 'esphome' CLI was not found in .venv or on PATH." -ForegroundColor Yellow
    Write-Host "Install ESPHome with:  uv venv --python 3.12 .venv; uv pip install esphome" -ForegroundColor Yellow
    Write-Host "Then compile/flash:    .\flash.cmd" -ForegroundColor Yellow
    exit 0
}

if ($Run) {
    if ($DevicePort) {
        & $esphomeExe run $YamlFile --device $DevicePort
    } else {
        & $esphomeExe run $YamlFile
    }
} elseif ($Compile) {
    & $esphomeExe compile $YamlFile
} else {
    Write-Host "==> Ready! Run '.\Build-Firmware.ps1 -Compile' or '.\Build-Firmware.ps1 -Run' to flash." -ForegroundColor Cyan
}
